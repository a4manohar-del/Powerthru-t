"""
PowerThru basic TinyML model: 16 window features -> {normal, fatigue, high_risk}.

Pipeline: train small MLP (~750 params) -> int8 TFLite -> C array for TFLite Micro.
Needs `pip install tensorflow` for the export step. Without TF it falls back to a
scikit-learn baseline so you can still check the data pipeline.

Run:  python tinyml_model.py                      (synthetic placeholder data)
      python tinyml_model.py --data my_feats.npz  (npz with X (N,16), y (N,), groups (N,))

Why features + MLP instead of your CNN-GRU: raw 1 kHz sEMG into a GRU is too heavy for
a small MCU. Extract features per second (cheap DSP), then classify a 30 s trend
vector. Your causal CNN-GRU is still a reasonable "v2" once the feature version works.
"""
import argparse
import numpy as np
from sklearn.metrics import classification_report, confusion_matrix
from powerthru_common import synth_dataset, CLASSES

N_IN, N_OUT = 16, len(CLASSES)


def split_by_user(X, y, g, test_frac=0.25, seed=0):
    """Hold out whole users (same lesson as your LOSO setup: never test on seen people)."""
    rng = np.random.default_rng(seed)
    users = np.unique(g)
    test_users = rng.choice(users, max(1, int(len(users) * test_frac)), replace=False)
    te = np.isin(g, test_users)
    return X[~te], y[~te], X[te], y[te]


def sklearn_baseline(Xtr, ytr, Xte, yte):
    from sklearn.neural_network import MLPClassifier
    m = MLPClassifier((24, 12), max_iter=400, random_state=0).fit(Xtr, ytr)
    return m.predict(Xte)


def train_keras(Xtr, ytr, Xte, yte):
    import tensorflow as tf
    tf.keras.utils.set_random_seed(42)
    model = tf.keras.Sequential([
        tf.keras.layers.Input((N_IN,)),
        tf.keras.layers.Dense(24, activation="relu"),
        tf.keras.layers.Dense(12, activation="relu"),
        tf.keras.layers.Dense(N_OUT, activation="softmax"),
    ])
    model.compile("adam", "sparse_categorical_crossentropy", metrics=["accuracy"])
    cw = {c: len(ytr) / (N_OUT * max(1, np.sum(ytr == c))) for c in range(N_OUT)}  # imbalance
    model.fit(Xtr, ytr, validation_split=0.15, epochs=60, batch_size=32, class_weight=cw,
              callbacks=[tf.keras.callbacks.EarlyStopping(patience=10, restore_best_weights=True)],
              verbose=0)
    model.summary()

    def rep():  # calibration data for int8 quantization
        for i in range(min(200, len(Xtr))):
            yield [Xtr[i:i + 1].astype(np.float32)]

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = rep
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    tfl = conv.convert()
    open("powerthru_model.tflite", "wb").write(tfl)
    write_c_array(tfl, "powerthru_model_data.h")
    print(f"int8 model: {len(tfl)} bytes")

    # check the QUANTIZED model, since that is what the band will actually run
    it = tf.lite.Interpreter(model_content=tfl); it.allocate_tensors()
    i, o = it.get_input_details()[0], it.get_output_details()[0]
    s, z = i["quantization"]
    preds = []
    for x in Xte:
        it.set_tensor(i["index"], np.clip(np.round(x / s + z), -128, 127).astype(np.int8)[None])
        it.invoke()
        preds.append(int(np.argmax(it.get_tensor(o["index"]))))
    return np.array(preds)


def write_c_array(data, path, name="powerthru_model_data"):
    with open(path, "w") as f:
        f.write(f"// generated by tinyml_model.py\n#include <cstdint>\n")
        f.write(f"alignas(16) const unsigned char {name}[] = {{\n")
        for k in range(0, len(data), 12):
            f.write("  " + ", ".join(f"0x{b:02x}" for b in data[k:k + 12]) + ",\n")
        f.write(f"}};\nconst unsigned int {name}_len = {len(data)};\n")
    print("wrote", path)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--data")
    a = ap.parse_args()
    if a.data:
        d = np.load(a.data); X, y, g = d["X"], d["y"], d["groups"]
    else:
        print("NOTE: using synthetic placeholder data -- metrics below mean nothing physiologically.")
        X, y, g = synth_dataset()
    Xtr, ytr, Xte, yte = split_by_user(X, y, g)
    try:
        pred = train_keras(Xtr, ytr, Xte, yte)
    except ImportError:
        print("TensorFlow not installed -> sklearn baseline only (no TFLite export).")
        pred = sklearn_baseline(Xtr, ytr, Xte, yte)
    print(classification_report(yte, pred, target_names=CLASSES, zero_division=0))
    print(confusion_matrix(yte, pred))
